-- Thêm cột category_id vào bảng courses
ALTER TABLE public.courses
ADD COLUMN IF NOT EXISTS category_id BIGINT REFERENCES public.course_categories(id) ON DELETE SET NULL;

-- Tự động map category_id cho các khoá học hiện có dựa trên từ khoá ở Title/Subtitle (tương đương với logic cứng cũ)
UPDATE public.courses
SET category_id = (SELECT id FROM public.course_categories WHERE slug = 'toeic')
WHERE UPPER(title) LIKE '%TOEIC%' OR UPPER(subtitle) LIKE '%TOEIC%';

UPDATE public.courses
SET category_id = (SELECT id FROM public.course_categories WHERE slug = 'cap3')
WHERE UPPER(title) LIKE '%CẤP 3%' OR UPPER(title) LIKE '%LỚP 10%' OR UPPER(title) LIKE '%THPT%' OR UPPER(title) LIKE '%TỐT NGHIỆP%' OR UPPER(title) LIKE '%THCS%'
   OR UPPER(subtitle) LIKE '%CẤP 3%' OR UPPER(subtitle) LIKE '%LỚP 10%' OR UPPER(subtitle) LIKE '%THPT%' OR UPPER(subtitle) LIKE '%THCS%';

UPDATE public.courses
SET category_id = (SELECT id FROM public.course_categories WHERE slug = 'basic')
WHERE category_id IS NULL;

