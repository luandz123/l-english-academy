
-- Add lesson_type to lessons
ALTER TABLE public.lessons ADD COLUMN IF NOT EXISTS lesson_type text NOT NULL DEFAULT 'video';

-- Create lesson_practices table for timed popup quizzes during video
CREATE TABLE public.lesson_practices (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lesson_id integer NOT NULL REFERENCES public.lessons(id) ON DELETE CASCADE,
  quiz_id integer REFERENCES public.quizzes(id) ON DELETE SET NULL,
  trigger_at_seconds integer NOT NULL DEFAULT 0,
  title text NOT NULL DEFAULT '',
  display_order integer NOT NULL DEFAULT 0,
  created_at timestamp with time zone DEFAULT now()
);

ALTER TABLE public.lesson_practices ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Admins manage lesson practices"
  ON public.lesson_practices FOR ALL
  USING (has_role(auth.uid(), 'admin'::app_role));

CREATE POLICY "Lesson practices viewable by all"
  ON public.lesson_practices FOR SELECT
  USING (true);
